import { memo } from "react";

interface BrandLogoProps {
  size?: number;
  className?: string;
  ariaLabel?: string;
  /** Цвет лепестков. Если не задан — наследуется от currentColor. */
  color?: string;
}

/**
 * SVG-версия клевера Серво-Юг. Inline для:
 *  - нулевого network-cost
 *  - currentColor наследования (адаптируется под dark/light)
 *  - чёткой отрисовки в любом размере
 *
 * Реальное лого — четыре лепестка-сердечка с двойной обводкой и центральным
 * медальоном «88» (две восьмёрки). В упрощённой SVG-версии медальон — белый
 * круг с символом ∞ (приблизительно передаёт оригинал, читается компактно).
 */
export const BrandLogo = memo(function BrandLogo({
  size = 32,
  className,
  ariaLabel = "Логотип Серво-Юг",
  color,
}: BrandLogoProps) {
  // Если ariaLabel пустой — SVG декоративный (внутри родителя со своим aria-label).
  // role="img" + пустой aria-label валит axe-core (svg-img-alt) — переключаемся
  // на aria-hidden=true для скринридеров.
  const isDecorative = ariaLabel.trim() === "";
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 64 64"
      xmlns="http://www.w3.org/2000/svg"
      {...(isDecorative
        ? { "aria-hidden": "true", focusable: false }
        : { role: "img", "aria-label": ariaLabel })}
      className={className}
      style={color ? { color } : undefined}
    >
      {/* Четыре лепестка-капли. Каждый — простая форма «сердечка» с
          закруглением. Используем currentColor для адаптации темы. */}
      <g fill="currentColor">
        {/* Верхний */}
        <path d="M32 6c-5 0-9 4-9 8.5 0 4 3 7 6 9.5 1 0.8 2 1.7 3 2.5 1-0.8 2-1.7 3-2.5 3-2.5 6-5.5 6-9.5C41 10 37 6 32 6z" />
        {/* Правый */}
        <path d="M58 32c0-5-4-9-8.5-9-4 0-7 3-9.5 6-0.8 1-1.7 2-2.5 3 0.8 1 1.7 2 2.5 3 2.5 3 5.5 6 9.5 6 4.5 0 8.5-4 8.5-9z" />
        {/* Нижний */}
        <path d="M32 58c5 0 9-4 9-8.5 0-4-3-7-6-9.5-1-0.8-2-1.7-3-2.5-1 0.8-2 1.7-3 2.5-3 2.5-6 5.5-6 9.5 0 4.5 4 8.5 9 8.5z" />
        {/* Левый */}
        <path d="M6 32c0 5 4 9 8.5 9 4 0 7-3 9.5-6 0.8-1 1.7-2 2.5-3-0.8-1-1.7-2-2.5-3-2.5-3-5.5-6-9.5-6C10 23 6 27 6 32z" />
      </g>
      {/* Центральный медальон — белый круг с символом «∞» */}
      <circle cx="32" cy="32" r="8" fill="#ffffff" />
      <circle cx="32" cy="32" r="8" fill="none" stroke="currentColor" strokeWidth="1.5" />
      {/* ∞ — две восьмёрки лежащие. Имитирует «88» оригинала. */}
      <path
        d="M28 32c0-1.5 1.5-3 3-3 1 0 1.7 0.5 2 1 0.3-0.5 1-1 2-1 1.5 0 3 1.5 3 3s-1.5 3-3 3c-1 0-1.7-0.5-2-1-0.3 0.5-1 1-2 1-1.5 0-3-1.5-3-3z"
        fill="currentColor"
      />
    </svg>
  );
});
