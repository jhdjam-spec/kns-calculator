"""α-коэффициенты по СП 30.13330.2020 §5.4 + прил. Б (табл. Б.1, Б.2).

Вероятностный метод расчёта максимального секундного расхода:

    q_max_sec = 5 × q_0 × α(P · N)

Где:
- q_0 — секундный расход воды одним водоразборным прибором, л/с
        (ванна 0.18, душ 0.09, унитаз 0.10, мойка 0.20)
- P — вероятность действия одного прибора в час максимального
       водопотребления (формула 5.3 СП 30)
- N — общее число приборов в здании
- α — коэффициент из табл. Б.1 (для горячей и холодной отдельно)
       или Б.2 (общий q_общ_max)

P рассчитывается:
    P_общ = (q_hr × U) / (q_0 × N × 3600)

где:
- q_hr — общая часовая норма потребления, л/(потр·ч) (из табл. А.2 СП 30)
- U — число потребителей
- 3600 — секунд в часе

Метод даёт точнее чем простое K_сут × K_час, особенно для крупных зданий
с большим числом приборов.
"""
from __future__ import annotations

from dataclasses import dataclass

# Табл. Б.1 СП 30.13330.2020 — коэффициент α для отдельных групп приборов
# (холодная или горячая вода). Ключ — P×N, значение — α.
# Полная таблица содержит ~40 строк, привожу ключевые точки + интерполяция.
_ALPHA_TABLE_B1: list[tuple[float, float]] = [
    (0.001, 0.200), (0.002, 0.202), (0.003, 0.205), (0.004, 0.207),
    (0.005, 0.210), (0.010, 0.230), (0.015, 0.247), (0.020, 0.262),
    (0.025, 0.276), (0.030, 0.289), (0.040, 0.314), (0.050, 0.338),
    (0.060, 0.360), (0.070, 0.382), (0.080, 0.402), (0.090, 0.422),
    (0.100, 0.442), (0.150, 0.535), (0.200, 0.620), (0.250, 0.700),
    (0.300, 0.778), (0.400, 0.927), (0.500, 1.069), (0.600, 1.205),
    (0.700, 1.336), (0.800, 1.464), (0.900, 1.589), (1.000, 1.711),
    (1.500, 2.281), (2.000, 2.821), (2.500, 3.343), (3.000, 3.852),
    (4.000, 4.844), (5.000, 5.811), (6.000, 6.760), (8.000, 8.620),
    (10.000, 10.448), (20.000, 19.215), (50.000, 44.957), (100.000, 87.322),
]


def alpha_b1(pn: float) -> float:
    """α по табл. Б.1 СП 30 (для холодной или горячей отдельно).

    Args:
        pn: произведение P × N (вероятность × число приборов).

    Returns:
        α по линейной интерполяции таблицы.
    """
    if pn <= 0:
        return 0.200    # минимум таблицы
    if pn <= _ALPHA_TABLE_B1[0][0]:
        return _ALPHA_TABLE_B1[0][1]
    if pn >= _ALPHA_TABLE_B1[-1][0]:
        # Экстраполяция: α ≈ 0.87 × (P·N) для больших значений
        return 0.87 * pn

    # Линейная интерполяция между соседними точками
    for i in range(len(_ALPHA_TABLE_B1) - 1):
        x1, y1 = _ALPHA_TABLE_B1[i]
        x2, y2 = _ALPHA_TABLE_B1[i + 1]
        if x1 <= pn <= x2:
            return y1 + (y2 - y1) * (pn - x1) / (x2 - x1)
    return _ALPHA_TABLE_B1[-1][1]


@dataclass
class AlphaCalculation:
    """Результат вероятностного расчёта по α-методу."""

    P: float                  # Вероятность действия одного прибора
    N: int                    # Число приборов
    PN: float                 # P × N
    alpha: float              # α по табл. Б.1
    q_0_lps: float            # секундный расход одного прибора, л/с
    q_max_sec_lps: float      # максимальный секундный расход, л/с
    q_max_hour_m3h: float     # тот же в часовых единицах (×3.6)
    method: str = "α-метод по СП 30 §5.4 / прил. Б"


def calc_q_max_sec_alpha(
    n_users: int,
    n_devices: int,
    q_hr_l_per_user_hour: float,
    q_0_lps: float = 0.20,
) -> AlphaCalculation:
    """Расчёт максимального секундного расхода по α-методу СП 30.

    Args:
        n_users: число пользователей (жителей, сотрудников).
        n_devices: число водоразборных приборов в здании.
        q_hr_l_per_user_hour: часовая норма потребления, л/(потр·ч)
                              (из табл. А.2 СП 30 — для жилых ~10-15).
        q_0_lps: секундный расход одного прибора, л/с (0.20 общ. норма).

    Returns:
        AlphaCalculation со всеми промежуточными значениями.

    Пример:
        ЖК на 50 квартир с 4 жителями (200 чел), 6 приборов на квартиру
        (300 приборов). q_hr = 10 л/потр·ч → P = 10×200 / (0.20·300·3600)
        = 0.0093 → P·N = 2.78 → α = 3.6 → Q = 5×0.20×3.6 = 3.6 л/с.
    """
    if n_devices <= 0:
        raise ValueError(f"n_devices должно быть > 0 (получено {n_devices})")

    # P — вероятность действия одного прибора (формула 5.3 СП 30)
    P = (q_hr_l_per_user_hour * n_users) / (q_0_lps * n_devices * 3600)
    PN = P * n_devices
    alpha = alpha_b1(PN)
    q_max = 5.0 * q_0_lps * alpha
    q_max_hour = q_max * 3.6

    return AlphaCalculation(
        P=round(P, 5),
        N=n_devices,
        PN=round(PN, 4),
        alpha=round(alpha, 3),
        q_0_lps=q_0_lps,
        q_max_sec_lps=round(q_max, 3),
        q_max_hour_m3h=round(q_max_hour, 2),
    )


# Типичные значения q_0 для разных приборов (л/с, СП 30 прил. А)
TYPICAL_DEVICE_FLOWS_LPS = {
    "bath": 0.18,        # ванна с душем
    "shower": 0.09,      # душевая кабина
    "toilet": 0.10,      # унитаз с бачком
    "sink": 0.20,        # мойка
    "washbasin": 0.07,   # умывальник
    "kitchen_sink": 0.20, # мойка кухонная
    "general": 0.20,     # общая норма
}


# Среднее число приборов на 1 жителя/сотрудника по типу здания
TYPICAL_DEVICES_PER_USER = {
    "residential_with_baths": 1.5,    # ванна+умывальник+мойка+унитаз+душ → ~1.5 на жителя
    "residential_with_showers": 1.2,
    "office": 0.3,                    # 1 унитаз и 1 мойка на 3-4 чел
    "school": 0.2,
    "hotel": 1.4,                     # на номер: ванна+мойка+унитаз
    "hospital": 1.0,                  # на койку
    "industrial": 0.15,
}


def estimate_n_devices(building_type: str, n_users: int) -> int:
    """Оценка числа водоразборных приборов по типу объекта."""
    rate = TYPICAL_DEVICES_PER_USER.get(building_type, 0.5)
    return max(1, int(round(n_users * rate)))
